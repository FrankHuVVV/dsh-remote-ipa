  /// `zh-CN` / `en`。
  final String language;
  final Map<String, String> _table;

  static const List<String> supportedLanguages = <String>['zh-CN', 'en'];

  static Strings of(String language) {
    final normalized = language.toLowerCase().startsWith('en') ? 'en' : 'zh-CN';
    return Strings._(normalized, normalized == 'en' ? _en : _zh);
  }

  bool get isEnglish => language == 'en';

  /// 取文案；缺键直接返回键名（界面上一眼能看出漏了哪条，而不是空白）。
  String get(String key) => _table[key] ?? '[$key]';

  String format(String key, Map<String, String> args) {
    var text = get(key);
    args.forEach((name, value) {
      text = text.replaceAll('{$name}', value);
    });
    return text;
  }

